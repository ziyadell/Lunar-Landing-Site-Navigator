/** Texts with a changing part: $1, $2 are the captured pieces (translated too when known). */
export const PATTERNS = PATTERNS_MORE;
for (const k in AR_MORE) AR[k] ??= AR_MORE[k];

export const t = (en: string) => (useSettings.getState().lang === 'ar' ? (AR[en] ?? en) : en);

const apply = () => {
  const l = useSettings.getState().lang;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
};
apply();
useSettings.subscribe(apply);

/** Switch language with a clean reload: view, site and time are in the URL, so they are kept. */
export function switchLang() {
  const s = useSettings.getState();
  s.set({ lang: s.lang === 'ar' ? 'en' : 'ar' });
  try {
    if (s.welcomeSeen) sessionStorage.setItem('lsn.skipWelcome', '1');
  } catch {
    /* storage unavailable: the welcome simply shows again */
  }
  window.location.reload();
}
